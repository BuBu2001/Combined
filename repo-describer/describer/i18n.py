"""Локализация: язык выбирается по системным переменным окружения (LANG/LC_ALL/LANGUAGE).

Русская локаль (ru*) -> русский, иначе английский. Можно переопределить флагом --lang.
"""
from __future__ import annotations

import locale
import os


def detect_lang() -> str:
    for var in ("LC_ALL", "LANGUAGE", "LC_MESSAGES", "LANG"):
        val = os.environ.get(var, "")
        if val:
            low = val.lower()
            if low.startswith("ru"):
                return "ru"
            if "-" in low or "_" in low or low.startswith("en"):
                return "en"
    try:
        sysloc = locale.getlocale()[0] or ""
        if sysloc.lower().startswith("ru"):
            return "ru"
    except Exception:
        pass
    return "en"


