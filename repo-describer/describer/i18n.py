_TABLES = {"ru": RUS, "en": ENG}


class Loc:
    def __init__(self, lang: str | None = None):
        self.lang = lang if lang in _TABLES else detect_lang()
        self._t = _TABLES[self.lang]

    def t(self, key: str, **kw) -> str:
        s = self._t.get(key, key)
        return s.format(**kw) if kw else s

    def kind(self, k: str) -> str:
        return self.t(f"kind_{k}")
